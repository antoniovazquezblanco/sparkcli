#ifndef _H_MATH_
#define _H_MATH_

#ifdef _WIN32
#include <stdlib.h>
#endif

/* Evaluate their arguments twice: do not pass expressions with side effects. */
#ifndef min
#define min(a, b) ((a) < (b) ? (a) : (b))
#endif

#ifndef max
#define max(a, b) ((a) > (b) ? (a) : (b))
#endif

#endif /* _H_MATH_ */
